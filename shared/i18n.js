let currentLang = 'en';

export function setCurrentLang(lang) {
  if (I18N[lang]) currentLang = lang;
}

export function getCurrentLang() {
  return currentLang;
}

// The saved choice wins; otherwise the browser's UI language if supported.
export function resolveLang(saved, browserLanguage) {
  if (I18N[saved]) return saved;
  const prefix = String(browserLanguage || '').split('-')[0];
  return I18N[prefix] ? prefix : 'en';
}

export function translate(lang, key, vars) {
  let s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  if (vars) {
    // A function replacement keeps "$" in names from APIs literal.
    for (const [name, value] of Object.entries(vars)) s = s.replaceAll(`{${name}}`, () => String(value));
  }
  return s;
}

export function t(key, vars) {
  return translate(currentLang, key, vars);
}
